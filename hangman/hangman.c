void printV(int x, int y, int n)
{
	for(int i = 0; i < n; i++ )
	{
		move(x++,y);
		printw(" ");
	}

}

void printH(int x, int y, int n)
{
	for(int i = 0; i < n; i++)
	{
		move(x,y++);
		printw(" ");
	}
}

